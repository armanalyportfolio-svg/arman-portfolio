const platformStyles: Record<
  SocialPlatform,
  { icon: (props: { className?: string }) => React.JSX.Element; accent: string }
> = {
  instagram: { icon: InstagramIcon, accent: "hover:text-pink-400 hover:border-pink-500/40" },
  linkedin: { icon: LinkedInIcon, accent: "hover:text-sky-400 hover:border-sky-500/40" },
  facebook: { icon: FacebookIcon, accent: "hover:text-blue-400 hover:border-blue-500/40" },
  whatsapp: { icon: WhatsAppIcon, accent: "hover:text-emerald-400 hover:border-emerald-500/40" },
  website: { icon: WebsiteIcon, accent: "hover:text-violet-400 hover:border-violet-500/40" },
};

// Social links from Contact settings, with icon + hover colour per platform.
// A WhatsApp entry without a URL links to the main WhatsApp number.
export function useSocialProfiles() {
  const { contact } = useSiteContent();
  return contact.socials.map((profile) => ({
    ...profile,
    url:
      profile.url ||
      (profile.platform === "whatsapp"
        ? whatsappUrl(contact.whatsappNumber, contact.whatsappMessage)
        : "#"),
    ...(platformStyles[profile.platform] ?? platformStyles.website),
  }));
}

